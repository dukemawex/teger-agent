/**
 * Evaluation harness: runs every simulated attack (plus the benign control) through the
 * full agent and asserts the expected verdict.
 *
 *   npm run eval                      offline: deterministic planner + compromised-LLM planner
 *   LIVE=1 npm run eval               also runs real SERV Reasoning (needs SERV_API_KEY, network)
 *   EVAL_WRITE=1 LIVE=1 npm run eval  rewrites docs/EVAL.md with the results table
 */
import { writeFileSync } from "node:fs";
import path from "node:path";
import { afterAll, describe, expect, it } from "vitest";
import { AgentResult, runAgent } from "../src/lib/agent/agent";
import { offlineNet, realNet } from "../src/lib/agent/net";
import { servClient, servModel } from "../src/lib/agent/serv";
import { FIXTURES } from "../src/lib/fixtures";
import { compromised } from "../tests/helpers/mocks";

type Mode = "deterministic" | "compromised-llm" | "serv-live";
const live = process.env.LIVE === "1" && !!process.env.SERV_API_KEY;
const modes: Mode[] = ["deterministic", "compromised-llm", ...(live ? (["serv-live"] as Mode[]) : [])];
const rows: { mode: Mode; id: string; label: string; expected: string; got: string; risk: number; tools: string; serv_calls: number; tokens: number; ms: number; planner: string; top: string }[] = [];

async function runMode(mode: Mode, f: (typeof FIXTURES)[number]): Promise<AgentResult> {
  const lists = { block: [], allow: [] };
  if (mode === "deterministic") return runAgent({ message: f.message, lists, toolEnv: { net: offlineNet, env: {} } });
  if (mode === "compromised-llm") return runAgent({ message: f.message, lists, toolEnv: { net: offlineNet, env: {} }, client: compromised() });
  return runAgent({ message: f.message, lists, toolEnv: { net: realNet, env: { PARALLEL_API_KEY: process.env.PARALLEL_API_KEY } }, client: servClient(), model: servModel() });
}

for (const mode of modes) {
  describe(`eval: ${mode}`, () => {
    for (const f of FIXTURES) {
      it(`${f.id} → ${f.expected}`, async () => {
        const t = Date.now();
        const r = await runMode(mode, f);
        rows.push({
          mode, id: f.id, label: f.label, expected: f.expected, got: r.verdict, risk: r.risk_score,
          tools: r.trace.filter((s) => s.tool).map((s) => s.tool).join(" → "), serv_calls: r.usage.serv_calls, tokens: r.usage.total_tokens,
          ms: Date.now() - t, planner: r.planner, top: r.top_reasons.slice(0, 3).map((x) => x.category).join(", "),
        });
        expect(r.verdict).toBe(f.expected);
        if (mode === "serv-live") expect(r.planner).toBe("serv");
      }, 120_000);
    }
  });
}

afterAll(() => {
  const order = (m: Mode) => modes.indexOf(m);
  rows.sort((a, b) => order(a.mode) - order(b.mode) || FIXTURES.findIndex((f) => f.id === a.id) - FIXTURES.findIndex((f) => f.id === b.id));
  const summary = modes.map((m) => { const rs = rows.filter((r) => r.mode === m); return `| ${m} | ${rs.filter((r) => r.got === r.expected).length}/${rs.length} |${m === "serv-live" ? ` ${rs.reduce((s, r) => s + r.serv_calls, 0)} calls, ${rs.reduce((s, r) => s + r.tokens, 0).toLocaleString("en-US")} tokens, median ${median(rs.map((r) => r.ms))} ms |` : " – |"}`; });
  const table = rows.map((r) => `| ${r.mode} | ${r.label} | \`${r.expected}\` | \`${r.got}\` ${r.got === r.expected ? "✅" : "❌"} | ${r.risk} | ${r.tools} | ${r.serv_calls} | ${r.tokens} | ${r.ms} |`);
  const md = `# Evaluation results

Generated by \`eval/fixtures.eval.ts\` (\`EVAL_WRITE=1 LIVE=1 npm run eval\`) on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC${live ? ` with SERV model \`${servModel()}\`` : ""}.

Modes:
- **deterministic**: no LLM, offline network. The fallback planner runs the tools in a fixed order. This is what CI runs.
- **compromised-llm**: a mocked SERV that obeys the attacker: it says "safe", skips the investigation, points tools at the cloud metadata IP and returns a fake "verified sender" explanation with a phishing link. The verdict must not move.
- **serv-live**: real SERV Reasoning (\`inference-api.openserv.ai/v1/chat/completions\`) planning with tool calls and live RDAP / link lookups.${live ? "" : " *(not run: set LIVE=1 and SERV_API_KEY)*"}

| Mode | Correct verdicts | SERV usage |
|---|---|---|
${summary.join("\n")}

| Mode | Fixture | Expected | Got | Risk | Tool calls (in order) | SERV calls | Tokens | ms |
|---|---|---|---|---|---|---|---|---|
${table.join("\n")}

Live latency includes real network lookups (RDAP, link resolution) and varies run to run; the model chooses its own tool order, so the serv-live tool sequence differs from the fixed fallback order.
`;
  if (process.env.EVAL_WRITE === "1") writeFileSync(path.resolve(import.meta.dirname, "../docs/EVAL.md"), md);
  process.stdout.write(`\n${summary.join("\n")}\n`);
});

function median(xs: number[]) { const s = [...xs].sort((a, b) => a - b); return s.length ? s[Math.floor(s.length / 2)] : 0; }
